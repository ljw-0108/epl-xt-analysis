"""Re-measure OpenPlay EPL 2025/26 data quality and write docs/data_quality_report.md.

Run after scripts/download_openplay_2526.py:
    python scripts/audit_openplay_2526.py
Reads only the checksum-verified raw files; every figure in the report is computed here.
"""
from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from epl_xt.openplay_adapter import SET_PIECE_FLAGS, convert_openplay_passes
from epl_xt.provenance_2526 import sha256
from epl_xt.quality import audit_events, audit_xt_grid

RAW = ROOT / "data/raw"
EVENT_FILE = RAW / "events_eng_2526.parquet"
CHECKSUMS = RAW / "openplay_checksums.json"
GRID_JSON = RAW / "karun_open_xt_12x8_v1.json"
REPORT = ROOT / "docs/data_quality_report.md"
AUDIT_COLUMNS = ["comp", "season", "match_id", "event_id", "team", "player", "type", "outcome",
                 "period", "minute", "second", "x", "y", "end_x", "end_y", "related_player_id", *SET_PIECE_FLAGS]


def set_piece_evidence(passes: pd.DataFrame) -> dict:
    def pct(mask, cond):
        part = passes.loc[mask]
        return f"{cond(part).mean():.2%}" if len(part) else "n/a"
    edge = lambda v: (v <= 2) | (v >= 98)  # noqa: E731
    checks = [
        ("q_CornerTaken", "start x >= 98 and y at a touchline (<=2 or >=98)", lambda d: (d["x"] >= 98) & edge(d["y"])),
        ("q_ThrowIn", "start y at a touchline (<=2 or >=98)", lambda d: edge(d["y"])),
        ("q_GoalKick", "start x <= 7 (own six-yard area)", lambda d: d["x"] <= 7),
        ("q_FreekickTaken", "none (any location)", None),
        ("q_IndirectFreekickTaken", "none (any location)", None),
    ]
    rows = [{"flag": f, "n": int(passes[f].sum()), "check": desc,
             "agree": pct(passes[f], cond) if cond else "—"} for f, desc, cond in checks]
    flags = passes[list(SET_PIECE_FLAGS)]
    restart = flags.any(axis=1)
    centre = passes["x"].between(49.5, 50.5) & passes["y"].between(49.5, 50.5)
    return {"rows": rows, "multi_flag": int((flags[["q_CornerTaken", "q_FreekickTaken", "q_ThrowIn", "q_GoalKick"]].sum(axis=1) > 1).sum()),
            "ifk": int(passes["q_IndirectFreekickTaken"].sum()),
            "ifk_in_fk": int((passes["q_IndirectFreekickTaken"] & passes["q_FreekickTaken"]).sum()),
            "restarts": int(restart.sum()), "open_play": int((~restart).sum()),
            "centre_untagged": int((centre & ~restart).sum())}


def main() -> None:
    for path in (EVENT_FILE, CHECKSUMS, GRID_JSON):
        if not path.is_file():
            raise SystemExit(f"Missing {path}; run scripts/download_openplay_2526.py first")
    expected = json.loads(CHECKSUMS.read_text(encoding="utf-8"))["events_eng_2526.parquet"]["sha256"]
    actual = sha256(EVENT_FILE)
    if actual != expected:
        raise SystemExit("Event file fails the publisher SHA-256; refusing to audit")
    events = pd.read_parquet(EVENT_FILE, columns=AUDIT_COLUMNS)
    ev = audit_events(events)
    _, adapter = convert_openplay_passes(events[["comp", "season", "match_id", "team", "player", "type",
                                                 "outcome", "x", "y", "end_x", "end_y", *SET_PIECE_FLAGS]])
    sp = set_piece_evidence(events.loc[events["type"].astype(str).eq("Pass")])
    grid = audit_xt_grid(json.loads(GRID_JSON.read_text(encoding="utf-8")))
    lines = [
        "# Data quality report — OpenPlay EPL 2025/26",
        "",
        f"Generated by `python scripts/audit_openplay_2526.py` on {date.today().isoformat()}. "
        "All numbers are measured from the files below; none are copied from earlier reports.",
        "",
        "## Sources",
        f"- Events: `events_eng_2526.parquet`, SHA-256 `{actual}` (matches publisher `checksums.json`).",
        f"- xT grid: `open_xt_12x8_v1.json` (Karun Singh), SHA-256 `{sha256(GRID_JSON)}`. "
        "The publisher provides no checksum; this hash is pinned in the downloader.",
        "",
        "## Events",
        "| Check | Result |",
        "|---|---|",
        f"| Source event rows | {ev['source_event_rows']:,} |",
        f"| comp / season values | {ev['comp_values']} / {ev['season_values']} |",
        f"| Full-row duplicates | {ev['full_row_duplicates']} |",
        f"| Duplicate (match_id, event_id, team) keys, all event types | {ev.get('event_key_duplicates_match_event_team')} |",
        f"| Matches / teams | {ev['matches']} / {ev['teams']} |",
        f"| Matches without exactly two passing teams | {ev['matches_without_exactly_two_passing_teams']} |",
        f"| Matches per team (min–max) | {min(ev['matches_per_team'].values())}–{max(ev['matches_per_team'].values())} |",
        "",
        "## Passes",
        "| Check | Result |",
        "|---|---|",
        f"| Pass rows | {ev['pass_rows']:,} |",
        f"| Outcomes | {ev['pass_outcomes']} |",
        f"| Nulls in required pass fields | {ev['pass_nulls']} |",
        f"| Content duplicates on {ev['pass_content_duplicate_key']} | {ev['pass_content_duplicates']} |",
        f"| Coordinate min | {ev['pass_coord_min']} |",
        f"| Coordinate max | {ev['pass_coord_max']} |",
        f"| Rows with any coordinate outside 0..100 | {ev['pass_coord_out_of_0_100']} |",
        f"| Periods | {ev.get('pass_periods')} |",
        f"| Players with passes / on more than one team | {ev['players_with_passes']} / {ev['players_on_multiple_teams']} |",
        f"| `related_player_id` non-null share on passes | {ev.get('pass_related_player_id_non_null_share', 0):.3f} |",
        "",
        "## Canonical conversion (`convert_openplay_passes`)",
        f"- {json.dumps(adapter)}",
        "",
        "## Set-piece flags (open-play filter)",
        "Provider qualifier flags on pass rows; location checks measure whether the flags agree with where restarts must start.",
        "",
        "| Flag | Passes | Location check | Agreement |",
        "|---|---|---|---|",
        *[f"| `{r['flag']}` | {r['n']:,} | {r['check']} | {r['agree']} |" for r in sp["rows"]],
        "",
        f"- Passes with more than one restart flag: {sp['multi_flag']}; indirect free kicks that are also `q_FreekickTaken`: {sp['ifk_in_fk']} of {sp['ifk']}.",
        f"- Restart passes excluded by the open-play filter: {sp['restarts']:,}; open-play passes: {sp['open_play']:,}.",
        f"- Untagged passes starting at the centre spot (49.5..50.5): {sp['centre_untagged']:,}. These look like kick-offs, but the source has no kick-off flag, so they stay in open play (no coordinate-based guessing).",
        "",
        "## xT grid",
        f"- {json.dumps(grid)}",
        "- Values rise toward column 11 (x=100), consistent with OpenPlay's rule that every team attacks toward x=100.",
        "- A vertical asymmetry of 0 means the y-axis orientation cannot change any xT value.",
        "- The grid is a published model fitted on older EPL data; it is not refit on 2025/26 and is not a win probability.",
        "",
        "## Interpretation limits",
        "- No pass recipient exists in the source (`related_player_id` is empty on passes), so no player-to-player network is shown.",
        "- The source has no player minutes, kick-off dates, or home/away flags; per-90 metrics, dates and home/away labels are not shown.",
        "- Players who changed clubs are always aggregated per (team, player).",
    ]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Wrote", REPORT)
    print(json.dumps({k: ev[k] for k in ("source_event_rows", "pass_rows", "matches_with_passes")}), json.dumps(adapter))


if __name__ == "__main__":
    main()
